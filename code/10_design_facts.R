# Design facts quoted in the Data and design section: waves and modes of the
# battery, the 2023 instrument by design, the floor item, sample points and
# interviewers, and the ISSP comparison series. Writes output/text/design_facts.md.

source(here::here("code", "helpers.R"))

allbus <- read_rds(clean("allbus_mn.rds"))
issp <- read_rds(clean("issp_ni.rds"))

pct <- \(x) scales::percent(x, accuracy = 0.1)

# Waves and modes of the battery
waves <- allbus |> count(year, mode) |> mutate(txt = glue::glue("{year} {mode} (n = {n})"))

# mn06 (Christian) at the floor, by arm in 2023
floor_item <- allbus |>
  filter(year == 2023, !is.na(mn06)) |>
  summarise(floor = mean(mn06 == 1), mean = mean(mn06), .by = arm) |>
  mutate(txt = glue::glue("{arm}: {pct(floor)} answer 1, mean {round(mean, 2)}"))

# Interviewers and sample points in the 2023 CAPI arm
capi <- allbus |>
  filter(year == 2023, arm == "CAPI") |>
  summarise(n = n(), n_int = n_distinct(interviewer, na.rm = TRUE), n_pt = n_distinct(point))
capi_cross <- allbus |>
  filter(year == 2023, arm == "CAPI", !is.na(interviewer)) |>
  distinct(interviewer, point) |>
  summarise(int_multi = sum(table(interviewer) > 1), pt_multi = sum(table(point) > 1))
point_arms <- allbus |>
  filter(year == 2023) |>
  distinct(point, arm) |>
  count(point) |>
  summarise(all_arms = sum(n == 3), n_pt = n())

# German ISSP series: mode and available descent items by wave
issp_de <- issp |>
  filter(germany) |>
  summarise(
    n = n(),
    mode = str_flatten(unique(replace_na(mode, "not recorded")), " / "),
    born = any(!is.na(born)), ancestry = any(!is.na(ancestry)),
    .by = year
  ) |>
  mutate(txt = glue::glue("{year}: {mode} (n = {n}); born {born}, ancestry {ancestry}"))

